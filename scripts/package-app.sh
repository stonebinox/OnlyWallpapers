#!/usr/bin/env bash
set -euo pipefail

# Single source of truth for the release version.
VERSION="0.1.0"
BUILD_NUMBER="1"
BUNDLE_ID="com.anoopsanthanam.onlywallpapers"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

echo "=== package-app: building OnlyWallpapers.app ==="

echo "[build] swift build -c release --arch arm64 --arch x86_64 --product OnlyWallpapers -Xswiftc -warnings-as-errors"
swift build -c release --arch arm64 --arch x86_64 --product OnlyWallpapers -Xswiftc -warnings-as-errors
echo "[build] PASS"

BIN_PATH="$(swift build -c release --arch arm64 --arch x86_64 --product OnlyWallpapers --show-bin-path)"
echo "[bin] BIN_PATH=$BIN_PATH"

APP="$REPO_ROOT/dist/OnlyWallpapers.app"
echo "[app] Target: $APP"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cp "$BIN_PATH/OnlyWallpapers" "$APP/Contents/MacOS/OnlyWallpapers"
echo "[app] Copied binary to Contents/MacOS/OnlyWallpapers"

# Contents/Resources (not the app root): a root-level bundle is "unsealed contents" and
# breaks codesign. SwiftPM's Bundle.module accessor checks Bundle.main.resourceURL first.
cp -R "$BIN_PATH/OnlyWallpapers_OnlyWallpapers.bundle" "$APP/Contents/Resources/OnlyWallpapers_OnlyWallpapers.bundle"
echo "[app] Copied resource bundle to Contents/Resources (Bundle.module resolves via Bundle.main.resourceURL)"

# Release builds ship NO video (black default). The dev machine's gitignored
# web/assets/bg.mp4 gets baked into the resource bundle; strip it from both layouts.
echo "[strip] Removing video files from packaged resource bundle..."
for _assets in \
    "$APP/Contents/Resources/OnlyWallpapers_OnlyWallpapers.bundle/web/assets" \
    "$APP/Contents/Resources/OnlyWallpapers_OnlyWallpapers.bundle/Contents/Resources/web/assets"; do
    if [ -d "$_assets" ]; then
        find "$_assets" -type f \( -iname '*.mp4' -o -iname '*.mov' -o -iname '*.webm' -o -iname '*.m4v' -o -iname '*.partial' \) -print -delete
    fi
done
# Webspike dev clips (if any) are not part of a release either.
find "$APP" -type f \( -iname '*.mp4' -o -iname '*.mov' -o -iname '*.webm' -o -iname '*.m4v' \) -print -delete
if [ -n "$(find "$APP" -type f \( -iname '*.mp4' -o -iname '*.mov' -o -iname '*.webm' -o -iname '*.m4v' \))" ]; then
    echo "[strip] FAIL: video files remain in $APP"
    exit 1
fi
echo "[strip] PASS: packaged app contains no video files"

# Dock icon: packaging/AppIcon.icns is the shipped icon (generated by scripts/make-icon.swift).
ICON_SRC="$REPO_ROOT/packaging/AppIcon.icns"
if [ ! -f "$ICON_SRC" ]; then
    echo "[icon] FAIL: $ICON_SRC is missing (the Dock icon is required; generate it with scripts/make-icon.swift)"
    exit 1
fi
cp "$ICON_SRC" "$APP/Contents/Resources/AppIcon.icns"
echo "[icon] Copied AppIcon.icns to Contents/Resources"

cat > "$APP/Contents/Info.plist" << PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key>
    <string>$BUNDLE_ID</string>
    <key>CFBundleExecutable</key>
    <string>OnlyWallpapers</string>
    <key>CFBundleName</key>
    <string>OnlyWallpapers</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>$VERSION</string>
    <key>CFBundleVersion</key>
    <string>$BUILD_NUMBER</string>
    <key>NSHumanReadableCopyright</key>
    <string>Copyright (c) 2026 Anoop Santhanam</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>LSMinimumSystemVersion</key>
    <string>14.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>NSLocationUsageDescription</key>
    <string>OnlyWallpapers uses your approximate location to determine local sunrise and sunset times and fetch current weather conditions for adaptive wallpaper tinting. Coordinates are rounded to 2 decimal places before any network request.</string>
    <key>NSLocationWhenInUseUsageDescription</key>
    <string>OnlyWallpapers uses your approximate location to determine local sunrise and sunset times and fetch current weather conditions for adaptive wallpaper tinting. Coordinates are rounded to 2 decimal places before any network request.</string>
</dict>
</plist>
PLIST

echo "[plist] Written $APP/Contents/Info.plist"
plutil -lint "$APP/Contents/Info.plist"
echo "[plist] PASS: plutil lint ok"

echo "[universal] Verifying binary is universal (arm64 + x86_64)..."
LIPO_ARCHS="$(lipo -archs "$APP/Contents/MacOS/OnlyWallpapers")"
echo "[universal] lipo -archs: $LIPO_ARCHS"
if echo "$LIPO_ARCHS" | grep -qw "x86_64" && echo "$LIPO_ARCHS" | grep -qw "arm64"; then
    echo "[universal] PASS: binary contains both x86_64 and arm64"
else
    echo "[universal] FAIL: expected both x86_64 and arm64, got: $LIPO_ARCHS"
    exit 1
fi

# Ad-hoc sign the whole bundle (after assembly AND video stripping).
echo "[sign] codesign --force --deep --sign - $APP"
codesign --force --deep --sign - "$APP"
codesign --verify --deep --strict "$APP"
echo "[sign] PASS: ad-hoc signature verifies (codesign --verify --deep --strict)"

ZIP="$REPO_ROOT/dist/OnlyWallpapers-$VERSION.zip"
rm -f "$ZIP" "$ZIP.sha256"
ditto -c -k --keepParent "$APP" "$ZIP"
(cd "$REPO_ROOT/dist" && shasum -a 256 "OnlyWallpapers-$VERSION.zip" > "OnlyWallpapers-$VERSION.zip.sha256")
echo "[zip] $ZIP"
echo "[zip] sha256: $(cut -d' ' -f1 "$ZIP.sha256")"

# Unversioned copy: the stable download URL is releases/latest/download/OnlyWallpapers.zip.
LATEST_ZIP="$REPO_ROOT/dist/OnlyWallpapers.zip"
rm -f "$LATEST_ZIP" "$LATEST_ZIP.sha256"
cp "$ZIP" "$LATEST_ZIP"
(cd "$REPO_ROOT/dist" && shasum -a 256 "OnlyWallpapers.zip" > "OnlyWallpapers.zip.sha256")
echo "[zip] $LATEST_ZIP"
echo "[zip] sha256: $(cut -d' ' -f1 "$LATEST_ZIP.sha256")"

echo ""
echo "Built: $APP"
echo "=== PASS: OnlyWallpapers $VERSION assembled, signed (ad-hoc), zipped (universal binary: arm64 + x86_64) ==="
